-- Needed so the exclusion constraint on bookings can combine equality on bigint
-- columns with range overlap. See docs/adr/0004-overlap-prevention.md.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE SCHEMA IF NOT EXISTS scheduler;

-- Every table below except tenants leads its primary key with tenant_id, and
-- every foreign key is tenant-scoped. That is what keeps the schema shardable
-- by tenant later. See docs/adr/0008-tenant-sharding-and-identifiers.md.

CREATE TABLE scheduler.tenants (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text        NOT NULL,
    status     text        NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE scheduler.services (
    tenant_id           bigint NOT NULL REFERENCES scheduler.tenants (id),
    id                  bigint GENERATED BY DEFAULT AS IDENTITY,
    name                text   NOT NULL,
    duration_minutes    int    NOT NULL DEFAULT 30 CHECK (duration_minutes > 0),
    granularity_minutes int    NOT NULL DEFAULT 30 CHECK (granularity_minutes > 0),
    min_notice_minutes  int    NOT NULL DEFAULT 0  CHECK (min_notice_minutes >= 0),
    max_horizon_days    int    NOT NULL DEFAULT 60 CHECK (max_horizon_days > 0),
    PRIMARY KEY (tenant_id, id)
);

CREATE TABLE scheduler.resources (
    tenant_id          bigint      NOT NULL REFERENCES scheduler.tenants (id),
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    type               text        NOT NULL,
    display_name       text        NOT NULL,
    timezone           text        NOT NULL,
    default_service_id bigint,
    active             boolean     NOT NULL DEFAULT true,
    metadata           jsonb       NOT NULL DEFAULT '{}'::jsonb,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, default_service_id) REFERENCES scheduler.services (tenant_id, id)
);

CREATE TABLE scheduler.requesters (
    tenant_id    bigint      NOT NULL REFERENCES scheduler.tenants (id),
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    external_ref text,
    display_name text,
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, id)
);

-- Recurring weekly windows in the resource's LOCAL time (ADR-0003).
CREATE TABLE scheduler.availability_rules (
    tenant_id       bigint   NOT NULL,
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    resource_id     bigint   NOT NULL,
    weekday         smallint NOT NULL CHECK (weekday BETWEEN 0 AND 6),
    starts_at_local time     NOT NULL,
    ends_at_local   time     NOT NULL,
    effective_from  date,
    effective_to    date,
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, resource_id) REFERENCES scheduler.resources (tenant_id, id),
    CHECK (ends_at_local > starts_at_local)
);

CREATE INDEX availability_rules_resource
    ON scheduler.availability_rules (tenant_id, resource_id, weekday);

CREATE TABLE scheduler.bookings (
    tenant_id       bigint      NOT NULL,
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    resource_id     bigint      NOT NULL,
    requester_id    bigint      NOT NULL,
    service_id      bigint      NOT NULL,
    starts_at       timestamptz NOT NULL,
    ends_at         timestamptz NOT NULL,
    status          text        NOT NULL DEFAULT 'confirmed' CHECK (status IN ('confirmed', 'cancelled')),
    meeting_url     text,
    idempotency_key text,
    metadata        jsonb       NOT NULL DEFAULT '{}'::jsonb,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, resource_id)  REFERENCES scheduler.resources  (tenant_id, id),
    FOREIGN KEY (tenant_id, requester_id) REFERENCES scheduler.requesters (tenant_id, id),
    FOREIGN KEY (tenant_id, service_id)   REFERENCES scheduler.services   (tenant_id, id),
    CHECK (ends_at > starts_at),

    -- The invariant (ADR-0004): one resource is never double-booked. The
    -- application pre-checks for a clean 409, but this is the authority.
    CONSTRAINT bookings_no_overlap EXCLUDE USING gist (
        tenant_id   WITH =,
        resource_id WITH =,
        tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (status = 'confirmed')
);

CREATE UNIQUE INDEX bookings_idempotency
    ON scheduler.bookings (tenant_id, idempotency_key)
    WHERE idempotency_key IS NOT NULL;

CREATE INDEX bookings_resource_window
    ON scheduler.bookings (tenant_id, resource_id, starts_at)
    WHERE status = 'confirmed';

CREATE INDEX bookings_requester_window
    ON scheduler.bookings (tenant_id, requester_id, starts_at);

CREATE TABLE scheduler.booking_events (
    tenant_id  bigint      NOT NULL,
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    booking_id bigint      NOT NULL,
    actor      text        NOT NULL,
    action     text        NOT NULL,
    at         timestamptz NOT NULL DEFAULT now(),
    payload    jsonb       NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, booking_id) REFERENCES scheduler.bookings (tenant_id, id)
);

